//! 스키마 비교(R53). Go `internal/db/schemadiff.go` 의 DB 가 필요 없는 쪽(스냅숏 모양·비교 표)이다.

use std::collections::{BTreeMap, BTreeSet};

use idb_core::result::QueryResult;

/// 스키마 하나의 구조다. 테이블 이름 → 정의.
#[derive(Clone, Debug, Default)]
pub struct Snapshot {
    pub schema: String,
    pub tables: BTreeMap<String, SnapTable>,
}

/// columns 는 열 번호 순서, indexes·constraints 는 이름 → 정의다. kind 는 TABLE·VIEW 등이고 view 는 뷰 정의다.
#[derive(Clone, Debug, Default)]
pub struct SnapTable {
    pub kind: String,
    pub view: String,
    pub columns: Vec<SnapColumn>,
    pub indexes: BTreeMap<String, String>,
    pub constraints: BTreeMap<String, String>,
}

/// def 는 "타입 NOT NULL DEFAULT …" 처럼 열 정의 글이다.
#[derive(Clone, Debug)]
pub struct SnapColumn {
    pub name: String,
    pub def: String,
}

/// relkind 의 낱말이다.
pub(crate) fn kind_word(kind: &str) -> &'static str {
    match kind {
        "r" => "TABLE",
        "p" => "PARTITIONED TABLE",
        "v" => "VIEW",
        "m" => "MATERIALIZED VIEW",
        "f" => "FOREIGN TABLE",
        _ => "",
    }
}

/// 열 정의 뒤에 붙는 기본값 절이다. identity·생성 열은 DEFAULT 대신 GENERATED 절이 된다.
pub(crate) fn column_default(identity: &str, generated: &str, default: &str) -> String {
    match (identity, generated) {
        ("a", _) => "GENERATED ALWAYS AS IDENTITY".into(),
        ("d", _) => "GENERATED BY DEFAULT AS IDENTITY".into(),
        (_, "s") => format!("GENERATED ALWAYS AS ({default}) STORED"),
        // PostgreSQL 18 가상 생성 열
        (_, "v") => format!("GENERATED ALWAYS AS ({default}) VIRTUAL"),
        _ if !default.is_empty() => format!("DEFAULT {default}"),
        _ => String::new(),
    }
}

/// 스냅숏에 싣는 열 정의 글이다.
pub(crate) fn column_def(typ: &str, not_null: bool, default: &str, identity: &str, generated: &str) -> String {
    let mut def = typ.to_string();
    if not_null {
        def.push_str(" NOT NULL");
    }
    let d = column_default(identity, generated, default);
    if !d.is_empty() {
        def.push(' ');
        def.push_str(&d);
    }
    def
}

/// 두 스냅숏의 다른 점을 표로 만든다. 구분은 +(오른쪽에만), −(왼쪽에만), ~(다름)이다.
/// 순서는 테이블 이름순, 한 테이블 안에서는 테이블 → 열(왼쪽 열 순서, 오른쪽에만 있는 열은 뒤) → 제약 → 인덱스 이름순이다.
/// 한쪽에만 있는 테이블은 테이블 줄 하나로만 보인다. 열 순서만 다른 것은 다름으로 치지 않는다.
pub fn diff_snapshots(a: &Snapshot, b: &Snapshot) -> QueryResult {
    let mut res = QueryResult {
        cols: ["구분", "대상", "왼쪽", "오른쪽"].map(String::from).to_vec(),
        types: Some(vec!["text".to_string(); 4]),
        ..Default::default()
    };
    for n in union_keys(&a.tables, &b.tables) {
        let (lt, rt) = (a.tables.get(n), b.tables.get(n));
        diff_row(
            &mut res,
            format!("테이블 {n}"),
            &table_label(lt),
            &table_label(rt),
            lt.is_some(),
            rt.is_some(),
        );
        let (Some(lt), Some(rt)) = (lt, rt) else { continue };
        let mut right: BTreeMap<&str, &str> = rt.columns.iter().map(|c| (c.name.as_str(), c.def.as_str())).collect();
        for c in &lt.columns {
            let r = right.remove(c.name.as_str());
            diff_row(&mut res, format!("열 {n}.{}", c.name), &c.def, r.unwrap_or(""), true, r.is_some());
        }
        // 오른쪽에만 있는 열도 오른쪽 열 순서로 보이려고 맵이 아니라 목록을 돈다
        for c in rt.columns.iter().filter(|c| right.contains_key(c.name.as_str())) {
            diff_row(&mut res, format!("열 {n}.{}", c.name), "", &c.def, false, true);
        }
        for k in union_keys(&lt.constraints, &rt.constraints) {
            let (l, r) = (lt.constraints.get(k), rt.constraints.get(k));
            diff_row(&mut res, format!("제약 {n}.{k}"), opt(l), opt(r), l.is_some(), r.is_some());
        }
        for k in union_keys(&lt.indexes, &rt.indexes) {
            let (l, r) = (lt.indexes.get(k), rt.indexes.get(k));
            diff_row(&mut res, format!("인덱스 {n}.{k}"), opt(l), opt(r), l.is_some(), r.is_some());
        }
    }
    res
}

fn opt(v: Option<&String>) -> &str {
    v.map_or("", String::as_str)
}

/// 한쪽에만 있거나 정의가 다를 때 줄을 더한다.
fn diff_row(res: &mut QueryResult, target: String, l: &str, r: &str, lok: bool, rok: bool) {
    let mark = match (lok, rok) {
        (_, false) => "−",
        (false, _) => "+",
        _ if l == r => return,
        _ => "~",
    };
    res.rows.push(vec![mark.into(), target, l.into(), r.into()]);
}

/// 두 맵의 키를 겹치지 않게 이름순으로 돌려준다.
fn union_keys<'a, V>(a: &'a BTreeMap<String, V>, b: &'a BTreeMap<String, V>) -> BTreeSet<&'a String> {
    a.keys().chain(b.keys()).collect()
}

/// 테이블 줄에 보일 글이다. 뷰는 정의까지 견준다.
fn table_label(t: Option<&SnapTable>) -> String {
    match t {
        None => String::new(),
        Some(t) if !t.view.is_empty() => format!("{} AS {}", t.kind, t.view),
        Some(t) => t.kind.clone(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn table(kind: &str, cols: &[(&str, &str)], cons: &[(&str, &str)], idx: &[(&str, &str)]) -> SnapTable {
        let map = |kv: &[(&str, &str)]| kv.iter().map(|(k, v)| (k.to_string(), v.to_string())).collect();
        SnapTable {
            kind: kind.into(),
            view: String::new(),
            columns: cols
                .iter()
                .map(|(n, d)| SnapColumn {
                    name: n.to_string(),
                    def: d.to_string(),
                })
                .collect(),
            constraints: map(cons),
            indexes: map(idx),
        }
    }

    fn snap(tables: Vec<(&str, SnapTable)>) -> Snapshot {
        Snapshot {
            schema: "s".into(),
            tables: tables.into_iter().map(|(n, t)| (n.to_string(), t)).collect(),
        }
    }

    #[test]
    fn 다른_점을_테이블_열_제약_인덱스_순으로_찍는다() {
        let a = snap(vec![
            (
                "t",
                table(
                    "TABLE",
                    &[("id", "integer NOT NULL"), ("a", "text"), ("gone", "text")],
                    &[("t_pkey", "PRIMARY KEY (id)")],
                    &[("t_a", "CREATE INDEX t_a ON t USING btree (a)")],
                ),
            ),
            ("only_left", table("TABLE", &[("x", "int")], &[], &[])),
        ]);
        let b = snap(vec![
            (
                "t",
                table(
                    "TABLE",
                    &[("new", "bigint"), ("a", "varchar(10)"), ("id", "integer NOT NULL")],
                    &[("t_pkey", "PRIMARY KEY (id)"), ("t_chk", "CHECK (id > 0)")],
                    &[],
                ),
            ),
            ("only_right", table("VIEW", &[], &[], &[])),
        ]);
        let res = diff_snapshots(&a, &b);
        let rows: Vec<String> = res.rows.iter().map(|r| r.join("|")).collect();
        assert_eq!(
            rows,
            [
                "−|테이블 only_left|TABLE|",
                "+|테이블 only_right||VIEW",
                "~|열 t.a|text|varchar(10)",
                "−|열 t.gone|text|",
                "+|열 t.new||bigint",
                "+|제약 t.t_chk||CHECK (id > 0)",
                "−|인덱스 t.t_a|CREATE INDEX t_a ON t USING btree (a)|",
            ]
        );
        assert!(diff_snapshots(&a, &a).rows.is_empty());
    }

    #[test]
    fn 기본값_절은_identity_생성열_DEFAULT_순이다() {
        assert_eq!(
            column_def("integer", true, "", "a", ""),
            "integer NOT NULL GENERATED ALWAYS AS IDENTITY"
        );
        assert_eq!(
            column_def("integer", false, "", "d", ""),
            "integer GENERATED BY DEFAULT AS IDENTITY"
        );
        assert_eq!(
            column_def("int", false, "(a * 2)", "", "s"),
            "int GENERATED ALWAYS AS ((a * 2)) STORED"
        );
        assert_eq!(column_def("text", false, "'x'::text", "", ""), "text DEFAULT 'x'::text");
        assert_eq!(column_def("text", false, "", "", ""), "text");
    }
}
