// editPG 는 ita 픽스처를 깐 접속을 돌려주고 끝나면 스키마를 지운다.
func editPG(t *testing.T) *PGConn {
	t.Helper()
	cs := NewClients()
	t.Cleanup(cs.Close)
	p, err := cs.PG(ctx(t), testPGConn(t))
	must(t, err)
	const drop = "drop schema if exists ita cascade"
	if _, err := p.pool.Exec(ctx(t), drop+";"+editFixture); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		c, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		if _, err := p.pool.Exec(c, drop); err != nil {
			t.Errorf("cleanup: %v", err)
		}
	})
	return p
}

