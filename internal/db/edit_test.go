func TestPG_출처는_캐시하지_않아_트랜잭션_안_DDL_을_되돌려도_맞는_열_이름을_쓴다(t *testing.T) {
	p := editPG(t)
	const sel = `select id, name, n from ita.t order by id`
	want := []string{"id", "name", "n"}
	for _, stmt := range []string{"begin", sel,
		"alter table ita.t rename column name to tmp", "alter table ita.t rename column n to name",
		"alter table ita.t rename column tmp to n"} {
		_, err := p.Run(ctx(t), stmt)
		must(t, err)
	}
	// 트랜잭션 안에서는 바뀐 이름이 보여야 한다. 결과 열 2(옛 name)는 이제 테이블 열 n 이다
	res, err := p.Run(ctx(t), `select id, n, name from ita.t order by id`)
	must(t, err)
	if res.Origin == nil || !slices.Equal(res.Origin.Cols, []string{"id", "n", "name"}) {
		t.Fatalf("트랜잭션 안 출처: %+v", res.Origin)
	}
	_, err = p.Run(ctx(t), "rollback")
	must(t, err)
	res, err = p.Run(ctx(t), sel)
	must(t, err)
	if res.Origin == nil || !slices.Equal(res.Origin.Cols, want) {
		t.Fatalf("ROLLBACK 뒤에도 바뀐 이름이 남았다: %+v", res.Origin)
	}
	// 다른 세션의 DDL 도 바로 따른다
	_, err = p.pool.Exec(ctx(t), "alter table ita.t rename column name to label")
	must(t, err)
	if _, err := p.Run(ctx(t), sel); err == nil {
		t.Fatal("이름이 바뀐 열은 조회가 실패해야 한다")
	}
	res, err = p.Run(ctx(t), `select id, label, n from ita.t order by id`)
	must(t, err)
	if res.Origin == nil || !slices.Equal(res.Origin.Cols, []string{"id", "label", "n"}) {
		t.Fatalf("다른 세션 DDL 뒤 출처: %+v", res.Origin)
	}
}

