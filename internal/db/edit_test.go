func TestPG_ApplyChanges_는_한_행이_아니면_전부_되돌린다(t *testing.T) {
	p := editPG(t)
	// 다른 세션이 그 사이 행을 지운 상황
	_, err := p.pool.Exec(ctx(t), `delete from ita.t where id = 2`)
	must(t, err)
	cs := ChangeSet{Table: TableRef{"ita", "t"}, PK: []string{"id"}, Changes: []Change{
		{Op: ChangeUpdate, Key: map[string]string{"id": "1"}, Values: map[string]*string{"name": strp("changed")}},
		{Op: ChangeInsert, Values: map[string]*string{"id": strp("20")}},
		{Op: ChangeUpdate, Key: map[string]string{"id": "2"}, Values: map[string]*string{"name": strp("gone")}},
	}}
	res, err := p.ApplyChanges(ctx(t), cs)
	if err == nil || !strings.Contains(err.Error(), "UPDATE failed: row (id=2) changed since it was read") {
		t.Fatalf("오류: %v", err)
	}
	if res == nil || res.InTx {
		t.Fatalf("실패 뒤 트랜잭션이 닫혀 있어야 한다: %+v", res)
	}
	got, err := p.Run(ctx(t), `select name from ita.t where id = 1 union all select name from ita.t where id = 20`)
	must(t, err)
	if len(got.Rows) != 1 || got.Rows[0][0] != "a" {
		t.Fatalf("앞 바꿈도 되돌려야 한다: %v", got.Rows)
	}
	// 지운 행 DELETE 도 마찬가지다
	cs.Changes = []Change{{Op: ChangeDelete, Key: map[string]string{"id": "2"}}}
	if _, err := p.ApplyChanges(ctx(t), cs); err == nil || !strings.Contains(err.Error(), "DELETE failed: row (id=2)") {
		t.Fatalf("DELETE 오류: %v", err)
	}
}

func TestPG_ApplyChanges_는_수동_트랜잭션_안에서_SAVEPOINT_만_되돌린다(t *testing.T) {
	p := editPG(t)
	_, err := p.Run(ctx(t), `begin`)
	must(t, err)
	_, err = p.Run(ctx(t), `insert into ita.t (id, name) values (30, 'outer')`)
	must(t, err)
	bad := ChangeSet{Table: TableRef{"ita", "t"}, PK: []string{"id"}, Changes: []Change{
		{Op: ChangeUpdate, Key: map[string]string{"id": "1"}, Values: map[string]*string{"name": strp("inner")}},
		{Op: ChangeUpdate, Key: map[string]string{"id": "1"}, Values: map[string]*string{"n": strp("not a number")}},
	}}
	res, err := p.ApplyChanges(ctx(t), bad)
	if err == nil || res == nil || !res.InTx {
		t.Fatalf("실패해도 바깥 트랜잭션은 열려 있어야 한다: %v %+v", err, res)
	}
	good := ChangeSet{Table: TableRef{"ita", "t"}, PK: []string{"id"}, Changes: []Change{
		{Op: ChangeUpdate, Key: map[string]string{"id": "30"}, Values: map[string]*string{"name": strp("edited")}},
	}}
	res, err = p.ApplyChanges(ctx(t), good)
	must(t, err)
	if !res.InTx {
		t.Fatal("성공해도 바깥 트랜잭션은 커밋하지 않는다")
	}
	got, err := p.Run(ctx(t), `select id, name from ita.t where id in (1, 30) order by id`)
	must(t, err)
	if len(got.Rows) != 2 || got.Rows[0][1] != "a" || got.Rows[1][1] != "edited" {
		t.Fatalf("트랜잭션 안 상태: %v", got.Rows)
	}
	// 바깥 트랜잭션에서 아직 커밋되지 않았다
	var n int
	must(t, p.pool.QueryRow(ctx(t), `select count(*) from ita.t where id = 30`).Scan(&n))
	if n != 0 {
		t.Fatal("다른 연결에서는 아직 보이지 않아야 한다")
	}
	_, err = p.Run(ctx(t), `rollback`)
	must(t, err)
	got, err = p.Run(ctx(t), `select count(*) from ita.t where id = 30`)
	must(t, err)
	if got.Rows[0][0] != "0" || got.InTx {
		t.Fatalf("rollback 뒤: %+v", got)
	}

	// 실패로 깨진 트랜잭션에서는 제출하지 않는다
	_, err = p.Run(ctx(t), `begin`)
	must(t, err)
	_, err = p.Run(ctx(t), `select 1/0`)
	if err == nil {
		t.Fatal("0 나누기는 실패해야 한다")
	}
	if _, err := p.ApplyChanges(ctx(t), good); err == nil || !strings.Contains(err.Error(), "aborted") {
		t.Fatalf("깨진 트랜잭션: %v", err)
	}
	_, err = p.Run(ctx(t), `rollback`)
	must(t, err)
}

