	_, err = p.Run(ctx(t), ins)
	must(t, err)
	again, err := p.Run(ctx(t), sel)
	must(t, err)
	if !slices.EqualFunc(orig.Rows, again.Rows, slices.Equal) {
		t.Fatalf("INSERT 왕복\n%v\n%v", orig.Rows, again.Rows)
	}
	_, err = p.Run(ctx(t), `update ita.t set name = 'x', n = 7, j = '{}', arr = null`)
