func TestBuildOrigin_PK_가_모두_있을_때만_만든다(t *testing.T) {
	rel := relOrigin{table: TableRef{"s", "t"}, editable: true, pk: []uint16{1, 2}, names: map[uint16]string{1: "a", 2: "b", 3: "c", 4: "d", 5: "e"},
		generated: map[uint16]bool{4: true}, identity: map[uint16]bool{5: true}}
	noPK, view := rel, rel
	noPK.pk, view.editable = nil, false
	cases := []struct {
		name    string
		rel     relOrigin
		attnums []uint16 // 0 은 식 열
		want    []string // 출처의 Cols, nil 이면 출처 없음
	}{
		{"식 열은 빈 이름", rel, []uint16{3, 0, 2, 1}, []string{"c", "", "b", "a"}},
		{"PK 일부가 빠짐", rel, []uint16{1, 3}, nil},
		{"모르는 열(시스템 열)", rel, []uint16{1, 2, 0xFFFF}, nil},
		{"같은 열이 두 번(자기 조인일 수 있음)", rel, []uint16{1, 2, 3, 3}, nil},
		{"PK 가 두 번", rel, []uint16{1, 2, 1}, nil},
		{"생성 열과 PK 가 아닌 IDENTITY ALWAYS 는 빈 이름", rel, []uint16{1, 2, 4, 5}, []string{"a", "b", "", ""}},
		{"PK 없는 테이블", noPK, []uint16{1, 2}, nil},
		{"뷰", view, []uint16{1, 2}, nil},
	}
	for _, c := range cases {
		fields := make([]pgconn.FieldDescription, len(c.attnums))
		for i, n := range c.attnums {
			if n != 0 {
				fields[i] = pgconn.FieldDescription{TableOID: 9, TableAttributeNumber: n}
			}
		}
		o := buildOrigin(&c.rel, fields)
		if c.want == nil {
			if o != nil {
				t.Errorf("%s: 출처가 없어야 한다: %+v", c.name, o)
			}
			continue
		}
		if o == nil || !slices.Equal(o.Cols, c.want) || !slices.Equal(o.PK, []string{"a", "b"}) || o.Table != rel.table {
			t.Errorf("%s: %+v", c.name, o)
		}
	}
}

