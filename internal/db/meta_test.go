func TestQuote_식별자와_리터럴을_이스케이프한다(t *testing.T) {
	if got := QuoteIdent(`a"b`); got != `"a""b"` {
		t.Errorf("ident: %q", got)
	}
	if got := QuoteLiteral(`it's`); got != `'it''s'` {
		t.Errorf("literal: %q", got)
	}
	if got := QuoteLiteral(`a\b'`); got != `E'a\\b'''` {
		t.Errorf("백슬래시 literal: %q", got)
	}
}

func TestBuildDDL_열_제약_인덱스_주석을_조립한다(t *testing.T) {
	m := &tableMeta{
		rel: relInfo{Kind: "r", Comment: "t's"},
		cols: []colInfo{
			{Name: "id", Type: "bigint", NotNull: true, Identity: "d"},
			{Name: "Q", Type: "integer", Default: "1"},
			{Name: "g", Type: "integer", Default: "(\"Q\" * 2)", Generated: "s", Comment: "생성"},
		},
		cons: []conInfo{{Name: "t_pkey", Def: "PRIMARY KEY (id)"}},
		idx: []idxInfo{
			{Name: "t_pkey", Def: "CREATE UNIQUE INDEX t_pkey ON s.t USING btree (id)", Backing: true},
			{Name: "t_q", Def: "CREATE INDEX t_q ON s.t USING btree (\"Q\")"},
		},
	}
	want := `CREATE TABLE "s"."t" (
    "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    "Q" integer DEFAULT 1,
    "g" integer GENERATED ALWAYS AS (("Q" * 2)) STORED,
    CONSTRAINT "t_pkey" PRIMARY KEY (id)
);
CREATE INDEX t_q ON s.t USING btree ("Q");
COMMENT ON TABLE "s"."t" IS 't''s';
COMMENT ON COLUMN "s"."t"."g" IS '생성';
`
	if got := buildDDL(TableRef{"s", "t"}, m); got != want {
		t.Fatalf("got\n%s\nwant\n%s", got, want)
	}
	virtual := &tableMeta{rel: relInfo{Kind: "r"}, cols: []colInfo{{Name: "v", Type: "integer", Default: "(a + 1)", Generated: "v"}}}
	if got := buildDDL(TableRef{"s", "t"}, virtual); got != "CREATE TABLE \"s\".\"t\" (\n    \"v\" integer GENERATED ALWAYS AS ((a + 1)) VIRTUAL\n);\n" {
		t.Fatalf("가상 생성 열: %q", got)
	}
	part := &tableMeta{
		rel:  relInfo{Kind: "r", ParentSchema: "s", ParentTable: "p", PartBound: "DEFAULT"},
		cols: []colInfo{{Name: "id", Type: "integer", NotNull: true}},
		idx:  []idxInfo{{Name: "c_id_idx", Def: "CREATE INDEX c_id_idx ON s.c USING btree (id)", Inherited: true}},
	}
	if got := buildDDL(TableRef{"s", "c"}, part); got != "CREATE TABLE \"s\".\"c\" PARTITION OF \"s\".\"p\" DEFAULT;\n" {
		t.Fatalf("파티션: %q", got)
	}
	view := &tableMeta{rel: relInfo{Kind: "m", ViewDef: " SELECT 1;"}}
	if got := buildDDL(TableRef{"s", "v"}, view); got != "CREATE MATERIALIZED VIEW \"s\".\"v\" AS\nSELECT 1;\n" {
		t.Fatalf("view: %q", got)
	}
}

func TestDescribeTable_열과_제약_인덱스를_보여준다(t *testing.T) {
	p := metaPG(t)
	res, err := p.DescribeTable(ctx(t), TableRef{"ddl_src", "Child Tbl"})
	if err != nil {
		t.Fatal(err)
	}
	want := [][]string{
		{"id", "bigint", "NO", "GENERATED ALWAYS AS IDENTITY", ""},
		{"parent_id", "integer", "NO", "", ""},
		{"code", "text", "NO", "DEFAULT 'x''y'::text", `c\d`},
		{"qty", "integer", "YES", "", ""},
		{"total", "numeric", "YES", "GENERATED ALWAYS AS ((qty * 2)) STORED", ""},
		{`Weird "Col"`, "character varying(20)", "YES", "", ""},
	}
	if !reflect.DeepEqual(res.Rows, want) {
		t.Fatalf("rows: %q", res.Rows)
	}
	for _, s := range []string{"comment: child's table", "PRIMARY KEY (id)", "FOREIGN KEY (parent_id) REFERENCES ddl_src.parent(id) ON DELETE CASCADE",
		"UNIQUE (parent_id, code)", "CHECK ((qty > 0))", "child_code_idx  CREATE INDEX child_code_idx"} {
		if !strings.Contains(res.Text, s) {
			t.Errorf("Text 에 %q 가 없다:\n%s", s, res.Text)
		}
	}
	if _, err := p.DescribeTable(ctx(t), TableRef{"ddl_src", "nope"}); err == nil || !strings.Contains(err.Error(), "not found") {
		t.Fatalf("없는 테이블: %v", err)
	}
}

func TestTableDDL_다른_스키마에서_실행하면_같은_테이블과_뷰가_된다(t *testing.T) {
	p := metaPG(t)
	c := ctx(t)
	if _, err := p.pool.Exec(c, "create schema ddl_dst"); err != nil {
		t.Fatal(err)
	}
	// 부모 → 자식 → 뷰 순서로 만들어야 FK·뷰가 참조할 대상이 있다
	refs := []string{"parent", "Child Tbl", "v", "events", "events_2026", "events_2026_1", "events_def"}
	src := map[string]string{}
	for _, name := range refs {
		ddl, err := p.TableDDL(c, TableRef{"ddl_src", name})
		if err != nil {
			t.Fatal(err)
		}
		src[name] = ddl
		// 인자 없는 Exec 는 simple protocol 이라 여러 문장을 한 번에 실행한다
		if _, err := p.pool.Exec(c, strings.ReplaceAll(ddl, "ddl_src", "ddl_dst")); err != nil {
			t.Fatalf("%s DDL 실행 실패: %v\n%s", name, err, ddl)
		}
	}
	for _, s := range []string{"GENERATED ALWAYS AS IDENTITY", "GENERATED ALWAYS AS ((qty * 2)) STORED", `"Weird ""Col""" character varying(20)`,
		`COMMENT ON COLUMN "ddl_src"."Child Tbl"."code" IS E'c\\d';`, "CREATE INDEX child_code_idx", `CONSTRAINT "Child Tbl_pkey" PRIMARY KEY (id)`} {
		if !strings.Contains(src["Child Tbl"], s) {
			t.Errorf("DDL 에 %q 가 없다:\n%s", s, src["Child Tbl"])
		}
	}
	for name, want := range map[string]string{
		"events_2026": `CREATE TABLE "ddl_src"."events_2026" PARTITION OF "ddl_src"."events" (
    CONSTRAINT "note_len" CHECK ((length(note) < 100))
) FOR VALUES FROM ('2026-01-01') TO ('2027-01-01') PARTITION BY LIST (id);
`,
		"events_2026_1": `CREATE TABLE "ddl_src"."events_2026_1" PARTITION OF "ddl_src"."events_2026" FOR VALUES IN (1);
CREATE INDEX events_2026_at_idx ON ddl_src.events_2026_1 USING btree (at);
`,
		"events_def": `CREATE TABLE "ddl_src"."events_def" PARTITION OF "ddl_src"."events" DEFAULT;
COMMENT ON TABLE "ddl_src"."events_def" IS '나머지';
`,
	} {
		if src[name] != want {
			t.Errorf("%s DDL\ngot\n%s\nwant\n%s", name, src[name], want)
		}
	}
	if !strings.HasPrefix(src["v"], `CREATE VIEW "ddl_src"."v" AS`) || !strings.Contains(src["v"], `COMMENT ON VIEW "ddl_src"."v" IS '뷰';`) {
		t.Errorf("뷰 DDL:\n%s", src["v"])
	}
	for _, name := range refs {
		dst, err := p.TableDDL(c, TableRef{"ddl_dst", name})
		if err != nil {
			t.Fatal(err)
		}
		if want := strings.ReplaceAll(src[name], "ddl_src", "ddl_dst"); dst != want {
			t.Errorf("%s DDL 이 다르다\ngot\n%s\nwant\n%s", name, dst, want)
		}
		a, err := p.DescribeTable(c, TableRef{"ddl_src", name})
		if err != nil {
			t.Fatal(err)
		}
		b, err := p.DescribeTable(c, TableRef{"ddl_dst", name})
		if err != nil {
			t.Fatal(err)
		}
		if !reflect.DeepEqual(a.Rows, b.Rows) || strings.ReplaceAll(a.Text, "ddl_src", "ddl_dst") != b.Text {
			t.Errorf("%s 카탈로그가 다르다\n%+v\n%+v", name, a, b)
		}
	}
}

// metaPG 는 ddl_src 픽스처를 깐 접속을 돌려주고 끝나면 두 스키마를 지운다.
func metaPG(t *testing.T) *PGConn {
	t.Helper()
	cs := NewClients()
	t.Cleanup(cs.Close)
	p, err := cs.PG(ctx(t), testPGConn(t))
	if err != nil {
		t.Fatal(err)
	}
	const drop = "drop schema if exists ddl_src, ddl_dst cascade"
	if _, err := p.pool.Exec(ctx(t), drop+";"+metaFixture); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		c, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		if _, err := p.pool.Exec(c, drop); err != nil {
			t.Errorf("cleanup: %v", err)
		}
	})
	return p
}
